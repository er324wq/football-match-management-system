USE football_admin_bench_20261017_a1;
CREATE TABLE `user` (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, username VARCHAR(50) NOT NULL UNIQUE, password VARCHAR(100) NOT NULL,
 nickname VARCHAR(50), phone VARCHAR(20), email VARCHAR(100), avatar VARCHAR(255), signature VARCHAR(255),
 role VARCHAR(20) DEFAULT 'user', status TINYINT DEFAULT 1, deleted TINYINT DEFAULT 0,
 create_time DATETIME DEFAULT CURRENT_TIMESTAMP, update_time DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 INDEX idx_username(username), INDEX idx_role(role), INDEX idx_phone(phone), INDEX idx_email(email)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
